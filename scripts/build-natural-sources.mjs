// Embed data/natural/*.lino into js/src/natural/sources.js so the library
// reads its controlled natural languages without file system access (in
// browsers, Deno and Bun alike). Rust embeds the same files with include_str!.
//
//   node scripts/build-natural-sources.mjs          rewrite the module
//   node scripts/build-natural-sources.mjs --check  fail if it is stale
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { URL } from 'node:url';

const folder = new URL('../data/natural/', import.meta.url);
const target = new URL('../js/src/natural/sources.js', import.meta.url);
const files = readdirSync(folder)
  .filter((file) => file.endsWith('.lino'))
  .sort();
const entries = files.map(
  (file) =>
    `  ${JSON.stringify(file)}: ${JSON.stringify(readFileSync(new URL(file, folder), 'utf8'))},`
);
const module = [
  '// Generated by scripts/build-natural-sources.mjs from data/natural/*.lino.',
  '// Edit the .lino files and run the script again; do not edit this file.',
  '// prettier-ignore',
  'export const naturalSources = {',
  ...entries,
  '};',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== module) {
    console.error(
      'js/src/natural/sources.js is stale: run node scripts/build-natural-sources.mjs'
    );
    process.exit(1);
  }
  console.log(`js/src/natural/sources.js matches ${files.length} files`);
} else {
  writeFileSync(target, module);
  console.log(`Wrote js/src/natural/sources.js from ${files.length} files`);
}
