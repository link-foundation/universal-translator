// Embed data/natural/*.lino into js/src/natural/sources.js so the library
// reads its controlled natural languages without file system access (in
// browsers, Deno and Bun alike). Rust embeds the same files with include_str!.
// A file larger than 100 kB (the vocabulary) gets a module of its own,
// sources-<name>.js, so the web build keeps each chunk below its size limit.
//
//   node scripts/build-natural-sources.mjs          rewrite the modules
//   node scripts/build-natural-sources.mjs --check  fail if one is stale
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { URL } from 'node:url';

const largeFile = 100 * 1024;
const header = [
  '// Generated by scripts/build-natural-sources.mjs from data/natural/*.lino.',
  '// Edit the .lino files and run the script again; do not edit this file.',
  '// prettier-ignore',
];
const folder = new URL('../data/natural/', import.meta.url);
const output = new URL('../js/src/natural/', import.meta.url);
const files = readdirSync(folder)
  .filter((file) => file.endsWith('.lino'))
  .sort();
const text = (file) => readFileSync(new URL(file, folder), 'utf8');
const large = files.filter((file) => text(file).length > largeFile);
const moduleOf = (file) => `sources-${file.replace(/\.lino$/, '')}.js`;
const nameOf = (file) =>
  file
    .replace(/\.lino$/, '')
    .replace(/-(.)/g, (_, letter) => letter.toUpperCase());

const modules = new Map([
  [
    'sources.js',
    [
      ...header.slice(0, 2),
      ...large.map(
        (file) => `import ${nameOf(file)} from './${moduleOf(file)}';`
      ),
      header[2],
      'export const naturalSources = {',
      ...files.map((file) =>
        large.includes(file)
          ? `  ${JSON.stringify(file)}: ${nameOf(file)},`
          : `  ${JSON.stringify(file)}: ${JSON.stringify(text(file))},`
      ),
      '};',
      '',
    ].join('\n'),
  ],
  ...large.map((file) => [
    moduleOf(file),
    [...header, `export default ${JSON.stringify(text(file))};`, ''].join('\n'),
  ]),
]);

const current = (name) =>
  existsSync(new URL(name, output))
    ? readFileSync(new URL(name, output), 'utf8')
    : undefined;

if (process.argv.includes('--check')) {
  const stale = [...modules].filter(
    ([name, module]) => current(name) !== module
  );
  if (stale.length) {
    console.error(
      `js/src/natural/${stale.map(([name]) => name).join(', ')} stale: run node scripts/build-natural-sources.mjs`
    );
    process.exit(1);
  }
  console.log(`js/src/natural/sources*.js match ${files.length} files`);
} else {
  for (const [name, module] of modules) {
    writeFileSync(new URL(name, output), module);
  }
  console.log(
    `Wrote ${[...modules.keys()].join(', ')} from ${files.length} files`
  );
}
