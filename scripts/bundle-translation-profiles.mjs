import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { URL } from 'node:url';

const dataDirectory = new URL('../data/', import.meta.url);
const bundledDirectory = new URL(
  '../js/src/translation/bundled/',
  import.meta.url
);
const check = process.argv.includes('--check');

function write(name, contents) {
  const destination = new URL(name, bundledDirectory);
  if (check) {
    if (readFileSync(destination, 'utf8') !== contents) {
      throw new Error(
        `Rebuild ${name} with node scripts/bundle-translation-profiles.mjs`
      );
    }
  } else {
    writeFileSync(destination, contents);
  }
}

const files = readdirSync(dataDirectory)
  .filter((name) => name.endsWith('.lino'))
  .sort();
const imports = [];
for (const [index, name] of files.entries()) {
  const source = readFileSync(new URL(name, dataDirectory), 'utf8');
  const literal = source
    .replaceAll('\\', '\\\\')
    .replaceAll('`', '\\`')
    .replaceAll('${', '\\${');
  const module = `${name}.js`;
  imports.push(`import registry${index} from './${module}';`);
  write(
    module,
    `// Generated from data/${name}.\nexport default \`${literal}\`;\n`
  );
}
write(
  'index.js',
  `// Generated by scripts/bundle-translation-profiles.mjs.\n${imports.join('\n')}\n\nexport default [\n${files.map((_, index) => `  registry${index},`).join('\n')}\n];\n`
);
