public final class StackArithmetic {
    public static void main(String[] args) {
        int start = -130;
        int factor = 2;
        int total = start * factor + 40000;
        long wide = 17L;
        wide = wide - (long) factor;
        System.out.print("Café 😀 ");
        System.out.println(total);
        System.out.println(wide / -2L);
        System.out.println(-wide % (long) factor);
        System.out.println((-factor + -1) / 4);
        System.out.print(-1);
        System.out.println();
    }
}
